--
-- ทุกค่าในไฟล์นี้มาจากคอลัมน์ที่ Excel ปล่อยให้พิมพ์เอง แล้วบานปลาย
-- ไซส์เสื้อ 16 ค่า (XL/Xl/2xl/2XL) · แหล่งทุน 7 ค่า (กยศ./กยศ/กู้ กยศ/กู้/กู้กยศ/กูู้้)
-- ระดับชั้น 3 ค่าที่เป็นค่าเดียวกัน (ป.ตรี/ป.ตรีี) — บีบลงเป็น enum ตามกฎเหล็กข้อ 4
--
-- แยกไฟล์จากไฟล์ที่เพิ่มคอลัมน์ เพราะ ALTER TYPE ... ADD VALUE
-- ใช้ค่าใหม่ใน transaction เดียวกับที่เพิ่มไม่ได้

-- ===== ขั้นสถานะ (Q1 Q8) =====
-- ไม่ยุบรวมสามมิติเดิมตาม ADR-0002 — แต่ละมิติใช้เฉพาะขั้นที่มันมีความหมาย
--   ผู้สนใจ  → follow_up_status
--   นักศึกษา → enrollment_status + payment_status (สำเนาจากหน่วยงานอื่น ADR-0003)
--   ปิดแฟ้ม  → ไม่ใช้มิติใดเลย
create type public.person_stage as enum ('ผู้สนใจ', 'นักศึกษา', 'ปิดแฟ้ม');

-- ===== ของคน =====
create type public.title_prefix as enum ('นาย', 'นาง', 'นางสาว', 'พระ');

-- ช่องทางที่ติดต่อเข้ามา — จำเป็นสำหรับคำถาม "ช่องทางไหนคุ้ม" ในหน้าหัวหน้าทีม
-- Excel แยกเป็น checkbox คนละคอลัมน์ (Facebook 2,967 · Line 293) แล้วคนที่สมัครจริง
-- อยู่อีกชีต จึงไม่มีใครเคยคำนวณอัตราแปลงต่อช่องทางได้
create type public.lead_source as enum (
  'Facebook', 'LINE', 'Walk in', 'โทรเข้า', 'แนะนำต่อ', 'อื่นๆ'
);

-- ===== ของใบสมัคร (เปลี่ยนได้ทุกปีที่สมัครใหม่ จึงไม่อยู่ที่ตาราง people) =====
create type public.degree_level as enum ('ปริญญาตรี', 'ปริญญาโท', 'ปริญญาเอก');
create type public.funding_type as enum ('ชำระตรง', 'กู้ กยศ.');
create type public.shirt_size   as enum ('S', 'M', 'L', 'XL', '2XL', '3XL');
create type public.box_set_state as enum (
  'ยังไม่ส่ง', 'ส่งแล้ว', 'รับเองที่มหาวิทยาลัย'
);

-- ===== เหตุการณ์ใหม่ =====
-- เปลี่ยนขั้น            — เจ้าหน้าที่กดตั้งค่าขั้นเอง (Q7) ระบบไม่เปลี่ยนให้เอง
-- รับทราบว่าขั้นไม่ตรง   — ปิดป้ายเตือนโดยผูกกับชุดใบสมัคร ณ ตอนนั้น (Q18)
-- ยกเลิกใบสมัคร          — ปิดช่องว่างเดิม: application_status มีค่า 'ยกเลิก'
--                          แต่ไม่มีเหตุการณ์ใดพาไปถึงได้ ใบสมัครเข้าระบบแล้วออกไม่ได้
alter type public.event_type add value if not exists 'เปลี่ยนขั้น';
alter type public.event_type add value if not exists 'รับทราบว่าขั้นไม่ตรง';
alter type public.event_type add value if not exists 'ยกเลิกใบสมัคร';

-- Excel ติดตามช่อง "ส่งใบสมัคร" เหมือนเอกสารอีกสี่ชนิด (กรอก 75–84% ทุกชีต)
-- หมายเหตุ: DOC_TYPES ใน TypeScript อ่านจาก enum นี้ตรง ๆ การเพิ่มค่าจึงทำให้
-- เกณฑ์ "เอกสารครบ" ขยับจาก 4 เป็น 5 ชนิด และ DOC_TYPE_SLUG ต้องมีคี่ใหม่
-- ต้องรัน npm run db:types แล้วเติม slug ทันที ไม่งั้น tsc ไม่ผ่าน
alter type public.doc_type add value if not exists 'ใบสมัคร';
