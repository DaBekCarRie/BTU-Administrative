import { describe, expect, it } from "vitest";

import { parseCsv, toCsv } from "./csv";

describe("CSV ของชีทเดิม", () => {
  it("อ่านเซลล์ที่มีจุลภาค เครื่องหมายคำพูด และขึ้นบรรทัดใหม่", () => {
    const text = 'ลำดับ,"วัน/เดือน/ปี \nที่ติดต่อ","พูดว่า ""สนใจ"", แต่ยังไม่สมัคร"\r\n1,2/9/2026,\r\n';
    expect(parseCsv(text)).toEqual([
      ["ลำดับ", "วัน/เดือน/ปี \nที่ติดต่อ", 'พูดว่า "สนใจ", แต่ยังไม่สมัคร'],
      ["1", "2/9/2026", ""],
    ]);
  });

  it("เขียนออกแล้วอ่านกลับได้ตรงทุกเซลล์ รวมวรรณยุกต์ซ้ำ", () => {
    const rows = [
      ["﻿ลำดับ", "ชื่อ", "หมายเหตุ"],
      ["1", "ฝ้้้าย", 'บอกว่า "โทรกลับ,\nพรุ่งนี้"'],
      ["", "", ""],
    ];
    expect(parseCsv(toCsv(rows))).toEqual(rows);
  });
});
